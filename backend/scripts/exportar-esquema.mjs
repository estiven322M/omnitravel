#!/usr/bin/env node
/**
 * Exporta el esquema REAL de la base (tablas, columnas, llaves, restricciones,
 * índices, funciones, disparadores y vistas) a `sql/000-esquema-base.sql`.
 *
 * Es la línea base de las migraciones versionadas (NC-04 de la auditoría):
 * 000 crea el esquema completo y 001, 002, 003… son los cambios posteriores.
 * Solo lee el catálogo de PostgreSQL; no modifica nada ni exporta datos.
 *
 *   npm run exportar-esquema
 */
import { writeFileSync } from 'node:fs';
import { conectar } from './conexion.mjs';

const SALIDA = new URL('../sql/000-esquema-base.sql', import.meta.url);
const q = (nombre) => (/^[a-z_][a-z0-9_]*$/.test(nombre) ? nombre : `"${nombre.replace(/"/g, '""')}"`);

const cliente = await conectar();
try {
  const { rows: extensiones } = await cliente.query(
    `select extname from pg_extension where extname <> 'plpgsql' order by extname`,
  );

  const { rows: tablas } = await cliente.query(
    `select c.oid, c.relname as nombre, obj_description(c.oid, 'pg_class') as comentario
       from pg_class c join pg_namespace n on n.oid = c.relnamespace
      where n.nspname = 'public' and c.relkind = 'r'
        and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype = 'e')
      order by c.relname`,
  );

  const { rows: columnas } = await cliente.query(
    `select a.attrelid as oid, a.attname as nombre, format_type(a.atttypid, a.atttypmod) as tipo,
            a.attnotnull as no_nulo, a.attidentity as identidad,
            pg_get_expr(d.adbin, d.adrelid) as defecto
       from pg_attribute a
       left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
      where a.attnum > 0 and not a.attisdropped
        and a.attrelid in (select c.oid from pg_class c join pg_namespace n on n.oid = c.relnamespace
                            where n.nspname = 'public' and c.relkind = 'r')
      order by a.attrelid, a.attnum`,
  );

  const { rows: restricciones } = await cliente.query(
    `select con.conrelid as oid, con.conname as nombre, con.contype as tipo,
            pg_get_constraintdef(con.oid) as definicion
       from pg_constraint con join pg_namespace n on n.oid = con.connamespace
      where n.nspname = 'public' and con.contype in ('p', 'u', 'c', 'f', 'x')
      order by con.conrelid, con.contype, con.conname`,
  );

  const { rows: indices } = await cliente.query(
    `select i.indexdef as definicion
       from pg_indexes i
      where i.schemaname = 'public'
        and not exists (select 1 from pg_constraint c where c.conname = i.indexname)
        and i.tablename in (select c.relname from pg_class c join pg_namespace n on n.oid = c.relnamespace
                             where n.nspname = 'public' and c.relkind = 'r'
                               and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype = 'e'))
      order by i.tablename, i.indexname`,
  );

  const { rows: funciones } = await cliente.query(
    `select pg_get_functiondef(p.oid) as definicion
       from pg_proc p join pg_namespace n on n.oid = p.pronamespace
      where n.nspname = 'public' and p.prokind in ('f', 'p')
        and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
      order by p.proname`,
  );

  const { rows: disparadores } = await cliente.query(
    `select pg_get_triggerdef(t.oid) as definicion
       from pg_trigger t join pg_class c on c.oid = t.tgrelid
       join pg_namespace n on n.oid = c.relnamespace
      where n.nspname = 'public' and not t.tgisinternal
      order by c.relname, t.tgname`,
  );

  const { rows: vistas } = await cliente.query(
    `select viewname as nombre, definition as definicion
       from pg_views where schemaname = 'public'
        and viewname not in ('geography_columns', 'geometry_columns')
      order by viewname`,
  );

  const lineas = [
    '-- OmniTravel · migración 000: esquema base (línea base de las migraciones)',
    '--',
    `-- Generado con \`npm run exportar-esquema\` desde la base de producción el ${new Date().toLocaleDateString('sv-SE', { timeZone: 'America/Bogota' })}.`,
    '-- Recrea la estructura completa en una base vacía (sin datos); después se',
    '-- aplican en orden 001, 002, 003… Usado también por las pruebas de integración.',
    '',
    ...extensiones.map((e) => `create extension if not exists ${q(e.extname)};`),
    '',
  ];

  for (const tabla of tablas) {
    const propias = columnas.filter((c) => c.oid === tabla.oid);
    const definiciones = propias.map((c) => {
      let linea = `  ${q(c.nombre)} ${c.tipo}`;
      if (c.identidad === 'a') linea += ' generated always as identity';
      else if (c.identidad === 'd') linea += ' generated by default as identity';
      else if (c.defecto?.startsWith('nextval(')) {
        linea = `  ${q(c.nombre)} ${c.tipo === 'bigint' ? 'bigserial' : c.tipo === 'smallint' ? 'smallserial' : 'serial'}`;
      } else if (c.defecto) linea += ` default ${c.defecto}`;
      if (c.no_nulo && !c.identidad && !c.defecto?.startsWith('nextval(')) linea += ' not null';
      return linea;
    });
    for (const r of restricciones.filter((x) => x.oid === tabla.oid && x.tipo !== 'f')) {
      definiciones.push(`  constraint ${q(r.nombre)} ${r.definicion}`);
    }
    lineas.push(`create table if not exists ${q(tabla.nombre)} (`, definiciones.join(',\n'), ');');
    if (tabla.comentario) {
      lineas.push(`comment on table ${q(tabla.nombre)} is '${tabla.comentario.replace(/'/g, "''")}';`);
    }
    lineas.push('');
  }

  const foraneas = restricciones.filter((r) => r.tipo === 'f');
  if (foraneas.length) {
    lineas.push('-- Llaves foráneas (después de crear todas las tablas)');
    for (const r of foraneas) {
      const tabla = tablas.find((t) => t.oid === r.oid);
      if (tabla) lineas.push(`alter table ${q(tabla.nombre)} add constraint ${q(r.nombre)} ${r.definicion};`);
    }
    lineas.push('');
  }

  if (indices.length) {
    lineas.push('-- Índices');
    lineas.push(...indices.map((i) => `${i.definicion.replace(/^CREATE (UNIQUE )?INDEX /, 'create $1index if not exists ')};`));
    lineas.push('');
  }
  if (funciones.length) {
    lineas.push('-- Funciones');
    lineas.push(...funciones.map((f) => `${f.definicion.trim()};\n`));
  }
  if (disparadores.length) {
    lineas.push('-- Disparadores');
    lineas.push(...disparadores.map((d) => `${d.definicion};`));
    lineas.push('');
  }
  if (vistas.length) {
    lineas.push('-- Vistas');
    lineas.push(...vistas.map((v) => `create or replace view ${q(v.nombre)} as\n${v.definicion.trim()}\n`));
  }

  writeFileSync(SALIDA, `${lineas.join('\n')}\n`);
  console.log(`✔ Esquema exportado: ${tablas.length} tablas, ${foraneas.length} llaves foráneas, ` +
    `${indices.length} índices, ${funciones.length} funciones, ${disparadores.length} disparadores, ${vistas.length} vistas.`);
  console.log('  Archivo: backend\\sql\\000-esquema-base.sql');
} finally {
  await cliente.end();
}
